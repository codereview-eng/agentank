// 预置地图库：10 张手工设计图，全部 17x17。
// 只写上半（y0..y8 共 9 行，含中线），下半由 180° 旋转自动补全（A↔B、a↔b 互换），
// 天然保证点对称——双方地形公平。图例同 mapFromAscii：
// '#'=墙 'D'=土堆 'g'=草丛 '*'=星星 'A'/'B'=出生点 '.'=空地
import { mapFromAscii } from './map.js';

const MIRROR = { A: 'B', B: 'A', a: 'b', b: 'a' };

function symRows(top) {
  const width = top[0].length;
  for (const r of top) {
    if (r.length !== width) throw new Error(`预置地图行宽不一致（应 ${width}）：${r}`);
  }
  const rows = top.slice();
  for (let i = top.length - 2; i >= 0; i--) {
    rows.push([...top[i]].reverse().map((c) => MIRROR[c] || c).join(''));
  }
  return rows;
}

