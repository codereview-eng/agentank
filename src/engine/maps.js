// 按 id 取图；每次返回全新对象（引擎会摧毁土堆/吃星，避免污染模板）。未知 id 返回 null。
export function presetMap(id) {
  const def = PRESET_MAPS.find((m) => m.id === id);
  return def ? mapFromAscii(symRows(def.top)) : null;
}
